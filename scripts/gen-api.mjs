// Generate TypeScript types for the backend API from its committed openapi.json.
//
//   npm run gen:api          write src/api/schema.d.ts
//   npm run gen:api:check    exit 1 if src/api/schema.d.ts doesn't match the spec (CI)
//
// Source (QP_OPENAPI_SOURCE): a file path or URL. Defaults to the sibling backend checkout.
// CI points it at the backend's main branch on GitHub.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = resolve(root, "src/api/schema.d.ts");
const source = process.env.QP_OPENAPI_SOURCE ?? "../query-pulse-backend/openapi.json";

const sourceUrl = /^https?:\/\//.test(source)
  ? new URL(source)
  : pathToFileURL(resolve(root, source));

const header =
  "// Generated by `npm run gen:api` from the backend's openapi.json. Do not edit by hand.\n\n";
const generated = header + astToString(await openapiTS(sourceUrl));

if (process.argv.includes("--check")) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (current !== generated) {
    console.error("src/api/schema.d.ts is out of date with the backend spec. Run: npm run gen:api");
    process.exit(1);
  }
  console.log("API types match the backend spec.");
} else {
  writeFileSync(outFile, generated);
  console.log(`Wrote ${outFile} from ${sourceUrl}`);
}
